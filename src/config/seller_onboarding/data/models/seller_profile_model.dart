import 'package:society_seva/features/seller_onboarding/domain/entities/seller_profile_entity.dart';

class SellerProfileModel extends SellerProfileEntity {
  const SellerProfileModel({
    required super.id,
    required super.userId,
    required super.displayName,
    required super.sellerType,
    required super.availabilityStatus,
    required super.approvalStatus,
    required super.fssaiStatus,
    required super.fssaiRequired,
    required super.renewalStatus,
    required super.totalListings,
    required super.averageRating,
    required super.rejectedOrders,
    required super.cancelledOrders,
    required super.totalOrders,
    required super.totalReviews,
    required super.address,
    required super.city,
    required super.state,
    required super.country,
    required super.pinCode,
    required super.createdAt,
    required super.updatedAt,
    super.societyId,
    super.businessName,
    super.bio,
    super.fssaiCertificateId,
    super.socialMediaLinks,
    super.websiteUrl,
    super.legalCompliance,
    super.latitude,
    super.longitude,
    super.geofencePolygon,
    super.deliveryRadiusKm,
    super.targetArea,
  });

  factory SellerProfileModel.fromJson(Map<String, dynamic> json) {
    return SellerProfileModel(
      id: json['id'].toString(),
      userId: json['userId'].toString(),
      displayName: json['displayName'] as String? ?? '',
      sellerType: json['sellerType'] as String? ?? '',
      availabilityStatus: json['availabilityStatus'] as String? ?? '',
      approvalStatus: json['approvalStatus'] as String? ?? '',
      fssaiStatus: json['fssaiStatus'] as String? ?? '',
      fssaiRequired: json['fssaiRequired'] as bool? ?? false,
      renewalStatus: json['renewalStatus'] as String? ?? '',
      totalListings: (json['totalListings'] as num?)?.toInt() ?? 0,
      averageRating: (json['averageRating'] as num?)?.toDouble() ?? 0.0,
      rejectedOrders: (json['rejectedOrders'] as num?)?.toInt() ?? 0,
      cancelledOrders: (json['cancelledOrders'] as num?)?.toInt() ?? 0,
      totalOrders: (json['totalOrders'] as num?)?.toInt() ?? 0,
      totalReviews: (json['totalReviews'] as num?)?.toInt() ?? 0,
      address: json['address'] as String? ?? '',
      city: json['city'] as String? ?? '',
      state: json['state'] as String? ?? '',
      country: json['country'] as String? ?? '',
      pinCode: json['pinCode'] as String? ?? '',
      createdAt: json['createdAt'] as String? ?? '',
      updatedAt: json['updatedAt'] as String? ?? '',
      societyId: json['societyId']?.toString(),
      businessName: json['businessName'] as String?,
      bio: json['bio'] as String?,
      fssaiCertificateId: json['fssaiCertificateId'] as String?,
      socialMediaLinks: json['socialMediaLinks'] as String?,
      websiteUrl: json['websiteUrl'] as String?,
      legalCompliance: json['legalCompliance'] as String?,
      latitude: (json['latitude'] as num?)?.toDouble(),
      longitude: (json['longitude'] as num?)?.toDouble(),
      geofencePolygon: json['geofencePolygon'] as String?,
      deliveryRadiusKm: (json['deliveryRadiusKm'] as num?)?.toDouble(),
      targetArea: json['targetArea'] as String?,
    );
  }

  SellerProfileEntity toEntity() => this;
}
